"""随机中国大陆手机号生成。

用途：AMD 注册表单里手机号是**服务端强制必填**的（实测：`VerificationMethod="email"`
+ 空 `PhoneNumber` 会返回 `{"Status":-100,"Message":"请输入您的手机号"}`）。当验证走
邮箱时，这个手机号**填谁的都行**（服务端不校验归属），但**不能为空**。

既然不校验归属，就没必要用真实号码 —— 用随机的合规号码即可。但要注意两件事：

1. **号段必须真实。** 服务端会做格式校验（11 位、`1` 开头、第二位 3-9，
   部分版本还查号段白名单）。用 `10000000000` 这种一眼假的号码会被前端或服务端
   直接拦掉，报错信息还可能被误读成「手机号已被占用」。
2. **同一个号不能注册两次。** 老板明确说过这点。所以批量注册时必须换号，
   而且要用 `random` 而不是固定序列 —— 否则同一批里重复的概率会很高。

这里维护的是**真实在用的号段前缀**（三大运营商公开号段），不编造。
号段会随时间新增，所以只作为「提高通过率」的白名单，而不是唯一来源：
传 `strict=False` 时仍会从完整 `1[3-9]xxxxxxxxx` 里取。
"""

from __future__ import annotations

import random

# 真实在用的号段（前 3 位）。来源是三大运营商公开号段，按需增补。
_PREFIXES = (
    # 中国移动
    "134", "135", "136", "137", "138", "139", "147", "150", "151", "152",
    "157", "158", "159", "172", "178", "182", "183", "184", "187", "188",
    "195", "197", "198",
    # 中国联通
    "130", "131", "132", "145", "146", "155", "156", "166", "167", "171",
    "175", "176", "185", "186", "196",
    # 中国电信
    "133", "149", "153", "173", "174", "177", "180", "181", "189", "190",
    "191", "193", "199",
)

# 已生成的号（进程内去重）。跨进程去重靠调用方落盘，这里只防同一批内重复。
_used: set[str] = set()


def random_cn_mobile(rng: random.Random | None = None, strict: bool = True) -> str:
    """生成一个随机的中国大陆 11 位手机号。

    `strict=True`（默认）用真实号段前缀；`strict=False` 只保证
    `1[3-9]` 开头 —— 当号段白名单被服务端更新、老前缀被拒时，
    可以放宽以重新试探。

    同一个进程内**不会返回重复号码**（`_used` 记着）。这对应老板说的
    「同一个手机号不能注册两次」—— 批量注册时每次都要换号。
    """
    r = rng or random
    for _ in range(1000):
        if strict:
            prefix = r.choice(_PREFIXES)          # 3 位
        else:
            prefix = "1" + r.choice("3456789")    # 2 位
        # 后缀长度由前缀长度决定 —— 写死 8 会让非严格分支只出 10 位，
        # 而这种「少一位」的号码本地校验看着像手滑，落到服务端就是格式错误。
        number = prefix + "".join(
            r.choice("0123456789") for _ in range(11 - len(prefix))
        )
        if number not in _used:
            _used.add(number)
            return number
    # 极端情况（号段被占满）：退化成完全随机，保证函数总能返回
    number = "1" + r.choice("3456789") + "".join(r.choice("0123456789") for _ in range(9))
    _used.add(number)
    return number


def is_valid_cn_mobile(number: str) -> bool:
    """按服务端同样宽松的规则校验：11 位、`1[3-9]` 开头、全数字。"""
    if len(number) != 11 or not number.isdigit():
        return False
    return number[0] == "1" and number[1] in "3456789"


def reset_used() -> None:
    """清空进程内已用号码（测试用）。"""
    _used.clear()
